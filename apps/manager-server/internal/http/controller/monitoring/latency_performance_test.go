// The path must refer to a fixture generated by the repository experiment.
// A separate marker table prevents mutations against a normal Manager DB.
func TestLatencyCoveringIndexAPIExperiment(t *testing.T) {
	path := os.Getenv("CPAMP_LATENCY_PERF_DB")
	if path == "" {
		t.Skip("opt-in API experiment on marked synthetic fixture")
	}
	info, err := os.Stat(path)
	if err != nil || !info.Mode().IsRegular() {
		t.Fatal("fixture file missing")
	}
	absolute, err := filepath.Abs(path)
	if err != nil {
		t.Fatal(err)
	}
	uriPath := filepath.ToSlash(absolute)
	if !strings.HasPrefix(uriPath, "/") {
		uriPath = "/" + uriPath
	}
	dsn := (&url.URL{Scheme: "file", Path: uriPath, RawQuery: "mode=ro"}).String()
	probe, err := sql.Open("sqlite", dsn)
	if err != nil {
		t.Fatal(err)
	}
	var count int
	markerErr := probe.QueryRow(`select event_count from cpamp_latency_benchmark_fixture`).Scan(&count)
	if err := probe.Close(); err != nil {
		t.Fatal(err)
	}
	if markerErr != nil || count <= 0 {
		t.Fatal("refusing database without synthetic fixture marker")
	}
	targetOnly := os.Getenv("CPAMP_LATENCY_PERF_API_TARGET_ONLY") == "1"
	if targetOnly && count != 3200000 {
		t.Fatalf("target-only API experiment requires exactly 3200000 events, got %d", count)
	}
	lock, err := processlock.Acquire(path)
	if err != nil {
		t.Fatal(err)
	}
	defer lock.Close()
	db, err := sql.Open("sqlite", path)
	if err != nil {
		t.Fatal(err)
	}
	defer db.Close()
	if targetOnly {
		var actualCount int
		if err := db.QueryRow(`select count(*) from usage_events`).Scan(&actualCount); err != nil {
			t.Fatal(err)
		}
		if actualCount != count {
			t.Fatalf("target-only API experiment requires a complete fixture: marker=%d usage_events=%d", count, actualCount)
		}
	}
	// Keep the experiment's DDL timeout/WAL policy aligned with CPAMP.
	if _, err := db.Exec(`pragma busy_timeout=5000`); err != nil {
		t.Fatal(err)
	}
	st, err := store.Open(path)
	if err != nil {
		t.Fatal(err)
	}
	defer st.Close()
	ctx := context.Background()
	const key = "cpamp_synthetic_benchmark_key"
	credential, err := security.NewAdminCredential(key, "synthetic benchmark")
	if err != nil {
		t.Fatal(err)
	}
	if err := st.SaveAdminCredential(ctx, credential); err != nil {
		t.Fatal(err)
	}
	exec := func(query string) {
		t.Helper()
		if _, err := db.Exec(query); err != nil {
			t.Fatal(err)
		}
	}
	const index = "idx_usage_events_ts_latency_ttft_cover"
	tabs := []string{"overview", "trends", "models", "apiKeys", "credentials"}
	daysToTest := []int64{30, 90, 120}
	rollups := []bool{false, true}
	if targetOnly {
		tabs = []string{"overview"}
		daysToTest = []int64{30}
		// Production defaults USAGE_DASHBOARD_HOURLY_ROLLUP_ENABLED to true.
		rollups = []bool{true}
		t.Log("TARGET events=3200000 days=30 tab=overview rollup=true")
	}
	profiles := map[string]monitoringsvc.Include{}
	for _, tab := range tabs {
		include := monitoringsvc.Include{Summary: true, SummaryProfile: "compact", Granularity: "day"}
		switch tab {
		case "overview":
			include.SummaryPercentiles = true
			include.SummaryComparison = true
			include.Timeline = true
			include.ModelStats = true
			include.ChannelShare = true
			include.APIKeyStats = true
			include.AnomalyPoints = true
		case "trends":
			include.SummaryComparison = true
			include.Timeline = true
			include.ModelStats = true
			include.APIKeyStats = true
			include.AnomalyPoints = true
		case "models":
			include.Timeline = true
			include.ModelStats = true
			include.APIKeyStats = true
		case "apiKeys":
			include.APIKeyStats = true
		case "credentials":
			include.CredentialStats = true
		}
		profiles[tab] = include
	}
	const base int64 = 1767225600000
	const day int64 = 86400000
	for _, rollup := range rollups {
		if rollup {
			started := time.Now()
			for {
				result, err := st.CatchUpUsageHourlyAggregate(ctx, 10000, base+120*day)
				if err != nil {
					t.Fatal(err)
				}
				if !result.Pending {
					break
				}
			}
			for {
				result, err := st.CatchUpUsagePricing(ctx, 10000, base+120*day)
				if err != nil {
					t.Fatal(err)
				}
				if !result.Pending {
					break
				}
			}
			t.Logf("ROLLUP events=%d preparation_ms=%.1f", count, float64(time.Since(started).Microseconds())/1000)
		}
		handler := &Handler{App: &app.Context{AdminAuthService: adminauthsvc.New(config.Config{}, st), MonitoringService: monitoringsvc.New(st, rollup)}}
		values := map[string][]float64{}
		digests := map[string]string{}
		references := map[string]map[string]any{}
		for round := -1; round < 5; round++ {
			order := []bool{false, true}
			if round%2 != 0 {
				order[0], order[1] = order[1], order[0]
			}
			for _, cover := range order {
				exec(`drop index if exists ` + index)
				if cover {
					exec(`create index ` + index + ` on usage_events(timestamp_ms,latency_ms,ttft_ms)`)
				}
				for _, days := range daysToTest {
					for _, tab := range tabs {
						name := fmt.Sprintf("api/%s/%dd/rollup=%t", tab, days, rollup)
						request := monitoringsvc.Request{FromMS: base + (120-days)*day, ToMS: base + 120*day, NowMS: base + 120*day, TimeZone: "UTC", Include: profiles[tab]}
						body, err := json.Marshal(request)
						if err != nil {
							t.Fatal(err)
						}
						req := httptest.NewRequest(http.MethodPost, "/v0/management/monitoring/analytics", bytes.NewReader(body))
						req.Header.Set("Authorization", "Bearer "+key)
						recorder := httptest.NewRecorder()
						var before, after runtime.MemStats
						runtime.ReadMemStats(&before)
						start := time.Now()
						handler.Handle(recorder, req)
						elapsed := float64(time.Since(start).Microseconds()) / 1000
						runtime.ReadMemStats(&after)
						if recorder.Code != http.StatusOK {
							t.Fatalf("%s code=%d body=%s", name, recorder.Code, recorder.Body.String())
						}
						var response map[string]any
						if err := json.Unmarshal(recorder.Body.Bytes(), &response); err != nil {
							t.Fatal(err)
						}
						delete(response, "generated_at_ms")
						// buildChannelShare emits a Go map in unspecified iteration
						// order even without an index change. Compare every row and
						// metric exactly, using auth_index as the unique row identity.
						if rows, ok := response["channel_share"].([]any); ok {
							seen := map[string]bool{}
							for _, row := range rows {
								key, ok := row.(map[string]any)["auth_index"].(string)
								if !ok || seen[key] {
									t.Fatal("ambiguous channel row identity")
								}
								seen[key] = true
							}
							sort.Slice(rows, func(i, j int) bool {
								return rows[i].(map[string]any)["auth_index"].(string) < rows[j].(map[string]any)["auth_index"].(string)
							})
						}
						canonical, err := json.Marshal(response)
						if err != nil {
							t.Fatal(err)
						}
						digest := fmt.Sprintf("%x", sha256.Sum256(canonical))
						if previous, ok := digests[name]; ok && previous != digest {
							latencyAPIDiff(t, references[name], response, "")
							t.Fatalf("API result mismatch %s cover=%t", name, cover)
						}
						digests[name] = digest
						references[name] = response
						if round >= 0 {
							variant := fmt.Sprintf("%s/cover=%t", name, cover)
							values[variant] = append(values[variant], elapsed)
						}
						t.Logf("API_SAMPLE name=%s cover=%t round=%d ms=%.3f allocated_bytes=%d response_bytes=%d", name, cover, round, elapsed, after.TotalAlloc-before.TotalAlloc, recorder.Body.Len())
					}
				}
			}
		}
		var names []string
		for name := range values {
			names = append(names, name)
		}
		sort.Strings(names)
		for _, name := range names {
			samples := values[name]
			sort.Float64s(samples)
			report := map[string]any{"name": name, "median_ms": samples[2], "p95_ms": samples[4], "min_ms": samples[0], "max_ms": samples[4], "runs": 5}
			data, err := json.Marshal(report)
			if err != nil {
				t.Fatal(err)
			}
			t.Log("API_PERF " + string(data))
		}
	}
	exec(`create index if not exists ` + index + ` on usage_events(timestamp_ms,latency_ms,ttft_ms)`)
}

func latencyAPIDiff(t *testing.T, before, after any, path string) {
	t.Helper()
	if reflect.DeepEqual(before, after) {
		return
	}
	if a, ok := before.(map[string]any); ok {
		if b, ok := after.(map[string]any); ok {
			for key, value := range a {
				latencyAPIDiff(t, value, b[key], path+"/"+key)
			}
			return
		}
	}
	if a, ok := before.([]any); ok {
		if b, ok := after.([]any); ok && len(a) == len(b) {
			for i := range a {
				latencyAPIDiff(t, a[i], b[i], fmt.Sprintf("%s/%d", path, i))
			}
			return
		}
	}
	t.Logf("API_DIFF %s before=%v after=%v", path, before, after)
}
