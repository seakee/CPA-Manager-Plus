package routing

import (
	"net/http"
	"net/url"
	"path"
	"strings"
)

// DiscoveryLifecycle is deliberately narrower than the Bootstrap domain
// classification. Lane A supplies the lifecycle observation; this package only
// decides the transport behavior of the already-owned fixed path.
type DiscoveryLifecycle string

const (
	DiscoveryActive      DiscoveryLifecycle = "active"
	DiscoveryCompleted   DiscoveryLifecycle = "completed"
	DiscoveryUnavailable DiscoveryLifecycle = "unavailable"
)

// DiscoveryLifecycleFunc lets startup code provide a read-only lifecycle view
// without making routing responsible for classification or persistence.
type DiscoveryLifecycleFunc func() DiscoveryLifecycle

// DiscoveryHandler enforces fixed-path ownership and method behavior. Active
// GET handling is delegated to the caller-owned discovery handler; a nil
// handler remains fail-closed so the canonical Public API is never activated by
// this transport seam alone.
type DiscoveryHandler struct {
	Lifecycle DiscoveryLifecycleFunc
	Active    http.Handler
}

func (h DiscoveryHandler) ServeHTTP(w http.ResponseWriter, r *http.Request) {
	if r == nil || r.URL == nil || r.URL.Path != BootstrapDiscoveryPath || !canonicalDiscoveryRequest(r) {
		writeGenericNotFound(w)
		return
	}
	lifecycle := DiscoveryUnavailable
	if h.Lifecycle != nil {
		lifecycle = h.Lifecycle()
	}
	if lifecycle != DiscoveryActive {
		writeGenericNotFound(w)
		return
	}
	switch r.Method {
	case http.MethodGet:
		if h.Active == nil {
			writeGenericNotFound(w)
			return
		}
		h.Active.ServeHTTP(w, r)
	case http.MethodOptions:
		w.WriteHeader(http.StatusNoContent)
	default:
		// The exact status is intentionally not part of the Phase4-01 wire
		// contract. Ownership is the contract: this response is generated by
		// Manager and never reaches Gateway.
		w.WriteHeader(http.StatusMethodNotAllowed)
	}
}

// ProtectFixedDiscovery captures exact and ambiguous variants before
// net/http.ServeMux can clean a path or issue a redirect. This prevents
// encoded separators, dot segments, duplicate slashes, backslashes, and
// trailing-slash aliases from reaching a different owner.
func ProtectFixedDiscovery(next http.Handler, discovery http.Handler) http.Handler {
	return ProtectFixedBootstrap(next, discovery)
}

// ProtectFixedBootstrap captures the complete bounded namespace before a mux
// can normalize aliases. Only canonical descendants reach the lifecycle owner.
func ProtectFixedBootstrap(next http.Handler, bootstrap http.Handler) http.Handler {
	return http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		if r == nil || r.URL == nil {
			writeGenericNotFound(w)
			return
		}
		if discoveryCandidate(r) {
			if CanonicalBootstrapRequest(r) && bootstrap != nil {
				bootstrap.ServeHTTP(w, r)
			} else {
				writeGenericNotFound(w)
			}
			return
		}
		next.ServeHTTP(w, r)
	})
}

func CanonicalBootstrapRequest(r *http.Request) bool {
	if r == nil || r.URL == nil || !CanonicalRequestPath(r.URL.Path) ||
		(r.URL.Path != BootstrapDiscoveryPath && !strings.HasPrefix(r.URL.Path, BootstrapDiscoveryPath+"/")) ||
		r.URL.EscapedPath() != r.URL.Path {
		return false
	}
	return r.RequestURI == "" || strings.SplitN(r.RequestURI, "?", 2)[0] == r.URL.Path
}

func writeGenericNotFound(w http.ResponseWriter) {
	w.Header().Del("Location")
	// http.NotFound supplies the ordinary net/http 404 body and no CPAMP
	// lifecycle or prefix-specific JSON.
	http.NotFound(w, &http.Request{Method: http.MethodGet})
}

func canonicalDiscoveryRequest(r *http.Request) bool {
	if r == nil || r.URL == nil || r.URL.Path != BootstrapDiscoveryPath {
		return false
	}
	escaped := r.URL.EscapedPath()
	return r.URL.RawPath == "" || (escaped == BootstrapDiscoveryPath && r.URL.RawPath == BootstrapDiscoveryPath)
}

func discoveryCandidate(r *http.Request) bool {
	if r == nil || r.URL == nil {
		return false
	}
	candidates := []string{r.URL.Path, r.URL.EscapedPath()}
	for _, original := range candidates {
		candidate := original
		for pass := 0; pass < 3; pass++ {
			if discoveryPathCandidate(candidate) {
				return true
			}
			decoded, err := url.PathUnescape(candidate)
			if err != nil || decoded == candidate {
				break
			}
			candidate = decoded
		}
	}
	return false
}

func discoveryPathCandidate(candidate string) bool {
	if candidate == BootstrapDiscoveryPath || strings.HasPrefix(candidate, BootstrapDiscoveryPath+"/") || strings.HasPrefix(candidate, BootstrapDiscoveryPath+"%") {
		return true
	}
	normalized := path.Clean(strings.ReplaceAll(candidate, "\\", "/"))
	return normalized == BootstrapDiscoveryPath || strings.HasPrefix(normalized, BootstrapDiscoveryPath+"/")
}
