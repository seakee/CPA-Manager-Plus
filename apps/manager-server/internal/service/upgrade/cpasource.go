// openManagedCPASource reads the source while the caller holds its ownership
// marker. Every refusal it returns is typed and happens before anything is
// written, because it only ever reads.
func openManagedCPASource(options cpaSourceOptions) (*cpaManagedSource, error) {
	directory, err := resolveCPADirectory(options)
	if err != nil {
		return nil, err
	}
	configPath := filepath.Join(directory, cpaConfigFileName)
	data, _, err := readRegularFileNoFollow(configPath, cpaMaxConfigBytes)
	if err != nil {
		if errors.Is(err, errRegularFileTooLarge) {
			return nil, newUpgradeError(UpgradeErrorCPASourceMissing,
				"the managed CPA config.yaml is larger than this import accepts, so it was not read", nil)
		}
		if errors.Is(err, ErrSourceSymlinked) {
			return nil, newUpgradeError(UpgradeErrorCPASourceMissing,
				"the managed CPA config.yaml may not be a symbolic link, so it was not read", err)
		}
		return nil, newUpgradeError(UpgradeErrorCPASourceMissing,
			"the 1.x stack holds no readable managed CPA config.yaml, so there is no CPA state to import", err)
	}
	document, err := decodeCPAConfigDocument(data)
	if err != nil {
		return nil, newUpgradeError(UpgradeErrorCPAConfigInvalid,
			"the managed CPA config.yaml is not a readable YAML mapping, so it was not imported", err)
	}
	source := &cpaManagedSource{
		directory:      directory,
		layout:         cpaLayoutV7,
		document:       map[string]any{},
		credentialData: map[string][]byte{},
		fingerprint:    digestBytes(data),
	}
	if err := source.gateVersion(document, options.CPAVersion); err != nil {
		return nil, err
	}
	if err := source.mapDocument(document); err != nil {
		return nil, err
	}
	if len(source.clientKeys) == 0 {
		return nil, newUpgradeError(UpgradeErrorCPAClientKeysMissing,
			"the 1.x CPA holds no client API key, so the destination could not be verified with the keys the import would install", nil)
	}
	if err := source.readCredentials(options.CPAAuthDirectory); err != nil {
		return nil, err
	}
	return source, nil
}

// resolveCPADirectory resolves the CPA directory beside the 1.x data directory.
func resolveCPADirectory(options cpaSourceOptions) (string, error) {
	raw := strings.TrimSpace(options.CPADirectory)
	if raw == "" {
		root, err := resolveLegacyRoot(options.LegacyRoot)
		if err != nil {
			return "", err
		}
		raw = filepath.Join(filepath.Dir(root), cpaSiblingDirectoryName)
	}
	absolute, err := filepath.Abs(raw)
	if err != nil {
		return "", fmt.Errorf("resolve the managed CPA directory: %w", err)
	}
	if _, err := statNoFollowDir(absolute); err != nil {
		if errors.Is(err, ErrSourceSymlinked) {
			return "", newUpgradeError(UpgradeErrorCPASourceMissing,
				"the managed CPA directory may not be a symbolic link, so it was not read", err)
		}
		return "", newUpgradeError(UpgradeErrorCPASourceMissing,
			"the 1.x stack holds no managed CPA directory beside the Manager data directory, so there is no CPA state to import", err)
	}
	return absolute, nil
}

var errRegularFileTooLarge = errors.New("regular file exceeds size limit")

func statNoFollowDir(path string) (os.FileInfo, error) {
	info, err := os.Lstat(path)
	if err != nil {
		return nil, err
	}
	if info.Mode()&os.ModeSymlink != 0 {
		return nil, fmt.Errorf("%w: %s is a symbolic link", ErrSourceSymlinked, filepath.Base(path))
	}
	if !info.IsDir() {
		return nil, fmt.Errorf("%s is not a directory", filepath.Base(path))
	}
	return info, nil
}

func openRegularFileNoFollow(path string) (*os.File, os.FileInfo, error) {
	lstatInfo, err := os.Lstat(path)
	if err != nil {
		return nil, nil, err
	}
	if lstatInfo.Mode()&os.ModeSymlink != 0 {
		return nil, nil, fmt.Errorf("%w: %s is a symbolic link", ErrSourceSymlinked, filepath.Base(path))
	}
	if !lstatInfo.Mode().IsRegular() {
		return nil, nil, fmt.Errorf("%s is not a regular file", filepath.Base(path))
	}
	file, err := os.Open(path)
	if err != nil {
		return nil, nil, err
	}
	fstatInfo, err := file.Stat()
	if err != nil {
		_ = file.Close()
		return nil, nil, err
	}
	if !fstatInfo.Mode().IsRegular() || !os.SameFile(lstatInfo, fstatInfo) {
		_ = file.Close()
		return nil, nil, fmt.Errorf("%w: %s changed before open", ErrSourceSymlinked, filepath.Base(path))
	}
	return file, fstatInfo, nil
}

func readRegularFileNoFollow(path string, maxBytes int64) ([]byte, os.FileInfo, error) {
	file, info, err := openRegularFileNoFollow(path)
	if err != nil {
		return nil, nil, err
	}
	defer func() { _ = file.Close() }()
	if info.Size() > maxBytes {
		return nil, info, errRegularFileTooLarge
	}
	data, err := io.ReadAll(io.LimitReader(file, maxBytes+1))
	if err != nil {
		return nil, info, err
	}
	if int64(len(data)) > maxBytes {
		return nil, info, errRegularFileTooLarge
	}
	return data, info, nil
}

// decodeCPAConfigDocument parses one CPA configuration file. Numbers keep their
// integer form (yaml returns ints for integers), so a value read here validates
// against the same gateway table the destination applies.
func decodeCPAConfigDocument(data []byte) (map[string]any, error) {
	var root yaml.Node
	decoder := yaml.NewDecoder(strings.NewReader(string(data)))
	if err := decoder.Decode(&root); err != nil {
		return nil, err
	}
	var trailing yaml.Node
	if err := decoder.Decode(&trailing); !errors.Is(err, io.EOF) {
		if err == nil {
			return nil, errors.New("the configuration file contains multiple YAML documents")
		}
		return nil, err
	}
	var document map[string]any
	if err := root.Decode(&document); err != nil {
		return nil, err
	}
	if document == nil {
		return nil, errors.New("the configuration file is empty")
	}
	if rawVersion, ok := lookupRootMappingNode(&root, cpaConfigVersionKey); ok {
		if rawVersion.Kind != yaml.ScalarNode || rawVersion.Tag != "!!int" || rawVersion.Value != "8" {
			document[cpaConfigVersionKey] = rawVersion.Value
		}
	}
	return normalizeDocument(document), nil
}

func lookupRootMappingNode(root *yaml.Node, key string) (*yaml.Node, bool) {
	if root == nil {
		return nil, false
	}
	node := root
	if node.Kind == yaml.DocumentNode {
		if len(node.Content) != 1 {
			return nil, false
		}
		node = node.Content[0]
	}
	if node.Kind != yaml.MappingNode {
		return nil, false
	}
	for index := 0; index+1 < len(node.Content); index += 2 {
		if node.Content[index].Value == key {
			return node.Content[index+1], true
		}
	}
	return nil, false
}

// normalizeDocument converts every nested mapping into the map[string]any shape
// the destination document is compared in. yaml.v3 already produces that shape
// for a map[string]any target; this walks the tree so a mapping nested under a
// non-string-keyed wrapper still reaches the same type, and it drops nothing.
func normalizeDocument(document map[string]any) map[string]any {
	out := make(map[string]any, len(document))
	for key, value := range document {
		out[key] = normalizeDocumentValue(value)
	}
	return out
}

func normalizeDocumentValue(value any) any {
	switch typed := value.(type) {
	case map[string]any:
		return normalizeDocument(typed)
	case map[any]any:
		out := make(map[string]any, len(typed))
		for key, item := range typed {
			out[fmt.Sprint(key)] = normalizeDocumentValue(item)
		}
		return out
	case []any:
		out := make([]any, 0, len(typed))
		for _, item := range typed {
			out = append(out, normalizeDocumentValue(item))
		}
		return out
	default:
		return value
	}
}

// gateVersion enforces CPA v8-only admission before any mutation.
//
// Every declared or stack-detected CPA release below 8.0.0 (or outside major 8)
// is refused with UpgradeErrorCPAVersionUnsupported. A file declaring
// `config-version: 8` still checks any operator-supplied `--cpa-version` or
// stack compose/environment `cli-proxy-api` declaration so a `< 8` stack image
// cannot slip past the gate. An unversioned file uses the legacy `v7` grammar
// that CPA v8 still loads and carries no release of its own, so an exact CPA v8
// release must be named by `--cpa-version` or the stack's compose/environment
// files.
func (s *cpaManagedSource) gateVersion(document map[string]any, declared string) error {
	rawConfigVersion, present := document[cpaConfigVersionKey]
	if present {
		version, ok := configVersionNumber(rawConfigVersion)
		if !ok || version != 8 {
			return newUpgradeError(UpgradeErrorCPAVersionUnsupported,
				"the managed CPA config.yaml declares a config-version this destination does not load, so it was not imported", nil)
		}
		s.layout = cpaLayoutV8Legacy
	}
	stackTag, status := cpaStackRelease(s.directory)
	var stackParsed cpaVersion
	if status == cpaStackReleaseResolved {
		parsed, ok := parseCPAVersion(stackTag)
		if !ok {
			return newUpgradeError(UpgradeErrorCPAVersionUnsupported,
				"the managed CPA release the stack declares is not an exact release, so it cannot be compared with the accepted v8 range and was not imported", nil)
		}
		if !parsed.atLeast(cpaImportFloor) {
			return newUpgradeError(UpgradeErrorCPAVersionUnsupported,
				fmt.Sprintf("the managed CPA source is release %s and this import accepts %s and above; upgrade the CPA inside the 1.x stack to CPA v8 before importing it",
					parsed.String(), CPAImportMinimumVersion), nil)
		}
		if parsed.major != 8 {
			return newUpgradeError(UpgradeErrorCPAVersionUnsupported,
				fmt.Sprintf("the managed CPA source declares release %s, outside the CPA v8 generation this import reads, so it was not imported",
					parsed.String()), nil)
		}
		stackParsed = parsed
	}
	declaredVersion := strings.TrimSpace(declared)
	if present {
		if declaredVersion == "" {
			switch status {
			case cpaStackReleaseAbsent:
				s.version = "v8"
				return nil
			case cpaStackReleaseUndetermined:
				return newUpgradeError(UpgradeErrorCPAVersionRequired,
					"the stack's compose/environment files declare a cli-proxy-api service without an exact CPA v8 release tag; pass --cpa-version to confirm the release before importing", nil)
			case cpaStackReleaseResolved:
				s.version = stackParsed.String()
				return nil
			}
		}
		parsed, ok := parseCPAVersion(declaredVersion)
		if !ok {
			return newUpgradeError(UpgradeErrorCPAVersionUnsupported,
				"the declared CPA version does not describe the v8 configuration this source holds, so it was not imported", nil)
		}
		if !parsed.atLeast(cpaImportFloor) {
			return newUpgradeError(UpgradeErrorCPAVersionUnsupported,
				fmt.Sprintf("the managed CPA source is release %s and this import accepts %s and above; upgrade the CPA inside the 1.x stack to CPA v8 before importing it",
					parsed.String(), CPAImportMinimumVersion), nil)
		}
		if parsed.major != 8 {
			return newUpgradeError(UpgradeErrorCPAVersionUnsupported,
				"the declared CPA version does not describe the v8 configuration this source holds, so it was not imported", nil)
		}
		s.version = declaredVersion
		return nil
	}
	if declaredVersion == "" {
		if status == cpaStackReleaseResolved {
			s.version = stackParsed.String()
			return nil
		}
		return newUpgradeError(UpgradeErrorCPAVersionRequired,
			"the managed CPA source uses the v7 layout and neither --cpa-version nor the stack's compose/environment files name an exact CPA v8 release; an unversioned layout carries no release of its own, and this import never guesses one", nil)
	}
	parsed, ok := parseCPAVersion(declaredVersion)
	if !ok {
		return newUpgradeError(UpgradeErrorCPAVersionUnsupported,
			"the managed CPA release the source declares is not an exact release, so it cannot be compared with the accepted v8 range and was not imported", nil)
	}
	if !parsed.atLeast(cpaImportFloor) {
		return newUpgradeError(UpgradeErrorCPAVersionUnsupported,
			fmt.Sprintf("the managed CPA source is release %s and this import accepts %s and above; upgrade the CPA inside the 1.x stack to CPA v8 before importing it",
				parsed.String(), CPAImportMinimumVersion), nil)
	}
	if parsed.major != 8 {
		return newUpgradeError(UpgradeErrorCPAVersionUnsupported,
			fmt.Sprintf("the managed CPA source declares release %s, outside the CPA v8 generation this import reads, so it was not imported",
				parsed.String()), nil)
	}
	s.version = parsed.String()
	return nil
}

// configVersionNumber reads the scalar `config-version` value. CPA v8 requires
// an integer 8 (`!!int` "8") and refuses any other type or value on load.
func configVersionNumber(value any) (int, bool) {
	switch typed := value.(type) {
	case int:
		return typed, true
	case int64:
		return int(typed), true
	case uint64:
		if typed > uint64(^uint(0)>>1) {
			return 0, false
		}
		return int(typed), true
	default:
		return 0, false
	}
}

// mapDocument maps the source onto the v8 document the destination accepts and
// collects everything it does not map.
func (s *cpaManagedSource) mapDocument(document map[string]any) error {
	consumed := map[string]bool{}
	consumedPrefixes := map[string]bool{}
	for _, hostPath := range cpaHostExclusivePaths {
		consumed[hostPath.path] = true
		if hostPath.whole {
			consumedPrefixes[hostPath.path] = true
		}
	}
	if configured, found := lookupFirst(document, "oauth.auth-dir", "auth-dir"); found {
		if raw, ok := configured.(string); ok {
			s.configuredAuthDir = strings.TrimSpace(raw)
		}
	}
	roots := map[string]bool{}
	knownContainers := map[string]bool{}
	addKnownPath := func(p string) {
		if p == "" {
			return
		}
		roots[firstSegment(p)] = true
		for idx := strings.IndexByte(p, '.'); idx >= 0; {
			knownContainers[p[:idx]] = true
			next := strings.IndexByte(p[idx+1:], '.')
			if next < 0 {
				break
			}
			idx += 1 + next
		}
	}
	for _, path := range cpaConfigPaths {
		addKnownPath(path.legacy)
		addKnownPath(path.current)
		for _, alias := range path.aliases {
			addKnownPath(alias)
		}
	}
	for _, hostPath := range cpaHostExclusivePaths {
		addKnownPath(hostPath.path)
	}
	for _, key := range []string{cpaClientKeyPathV8, cpaClientKeyPathV7} {
		addKnownPath(key)
	}
	addKnownPath("oauth.providers.codex.live-media-relay.allow-private-remote-ips")
	addKnownPath("codex.live-media-relay.allow-private-remote-ips")

	for _, path := range cpaConfigPaths {
		value, presence := s.sourceValue(document, path)
		if presence == documentMissing {
			continue
		}
		if presence == documentNull {
			markPathConsumed(consumed, consumedPrefixes, path)
			continue
		}
		if path.grouped {
			grouped, ok := groupLegacyAPIKeys(value, sectionProvider(path.current))
			if !ok {
				s.addManual(cpaManualItem{
					item:        "section:" + path.current,
					reason:      "value_shape_unsupported",
					instruction: "The source " + path.legacy + " entries are not the list CPA reads. Re-add this provider's keys on the destination Console.",
				})
				markPathConsumed(consumed, consumedPrefixes, path)
				continue
			}
			value = grouped
		}
		if path.current == "credentials.concurrency" {
			cleaned, keep := stripConcurrencySourceRevisions(value)
			if !keep {
				markPathConsumed(consumed, consumedPrefixes, path)
				continue
			}
			value = cleaned
		}
		setDocumentPath(s.document, path.current, value)
		markPathConsumed(consumed, consumedPrefixes, path)
	}

	// Handle deprecated codex live-media-relay allow-private-remote-ips when
	// neither canonical nor legacy disable-private-remote-ips was explicitly set.
	s.applyLiveRelayAllowPrivateRemoteIPs(document, consumed)

	// The client key list is installed by the destination stage and proved by
	// cpa.VerifyV8Adoption, so the source spelling that carries it is consumed
	// here: it is copied, just not as configuration. Only that spelling is
	// consumed — a canonical v8 `api-keys` mapping is the provider groups, and
	// consuming it wholesale would hide every family the table does not map.
	keys, clientKeyPath, found := cpaClientKeyList(document, consumed)
	if found {
		consumed[clientKeyPath] = true
		s.clientKeys = keys
	} else {
		// No client key is a refusal the caller makes after mapping; leaving the
		// list empty here keeps the reason in one place.
		s.clientKeys = nil
	}

	s.reportUnmapped(document, roots, knownContainers, consumed, consumedPrefixes)
	return nil
}

func markPathConsumed(consumed, consumedPrefixes map[string]bool, path cpaConfigPath) {
	mark := func(p string) {
		if p == "" {
			return
		}
		consumed[p] = true
		if path.whole {
			consumedPrefixes[p] = true
		}
	}
	mark(path.current)
	mark(path.legacy)
	for _, alias := range path.aliases {
		mark(alias)
	}
}

func stripConcurrencySourceRevisions(raw any) (any, bool) {
	mapping, ok := raw.(map[string]any)
	if !ok {
		return raw, true
	}
	clean := make(map[string]any, len(mapping))
	for key, item := range mapping {
		if key == "lifecycle-config-revision" || key == "observation-barrier-revision" {
			continue
		}
		clean[key] = item
	}
	if len(clean) == 0 {
		return nil, false
	}
	return clean, true
}

func (s *cpaManagedSource) applyLiveRelayAllowPrivateRemoteIPs(document map[string]any, consumed map[string]bool) {
	const (
		canonicalDisable = "oauth.providers.codex.live-media-relay.disable-private-remote-ips"
		legacyDisable    = "codex.live-media-relay.disable-private-remote-ips"
		canonicalAllow   = "oauth.providers.codex.live-media-relay.allow-private-remote-ips"
		legacyAllow      = "codex.live-media-relay.allow-private-remote-ips"
	)
	_, canonicalSet := lookupDocumentPath(document, canonicalDisable)
	_, legacySet := lookupDocumentPath(document, legacyDisable)
	_, canonicalAllowPresence := lookupDocumentPath(document, canonicalAllow)
	_, legacyAllowPresence := lookupDocumentPath(document, legacyAllow)
	if canonicalAllowPresence != documentMissing {
		consumed[canonicalAllow] = true
	}
	if legacyAllowPresence != documentMissing {
		consumed[legacyAllow] = true
	}
	if canonicalSet != documentMissing || legacySet != documentMissing {
		return
	}
	for _, candidate := range []string{canonicalAllow, legacyAllow} {
		value, presence := lookupDocumentPath(document, candidate)
		if presence == documentMissing {
			continue
		}
		if presence == documentNull {
			return
		}
		allow, ok := value.(bool)
		if !ok {
			s.addManual(cpaManualItem{
				item:        "config:" + candidate,
				reason:      "value_shape_unsupported",
				instruction: "The source " + candidate + " flag is not a boolean. Set disable-private-remote-ips on the destination Console.",
			})
			return
		}
		setDocumentPath(s.document, canonicalDisable, !allow)
		return
	}
}

// sourceValue reads one table path from the source. The canonical v8 spelling
// wins by presence (including null) over intermediate aliases, which win over
// the legacy v7 spelling, matching CPA's flattenV8 precedence (config_v8.go).
func (s *cpaManagedSource) sourceValue(document map[string]any, path cpaConfigPath) (any, documentPresence) {
	if path.current != "" {
		if value, presence := lookupDocumentPath(document, path.current); presence != documentMissing {
			return value, presence
		}
	}
	for _, alias := range path.aliases {
		if alias == "" || alias == path.current {
			continue
		}
		if value, presence := lookupDocumentPath(document, alias); presence != documentMissing {
			return value, presence
		}
	}
	if path.legacy != "" && path.legacy != path.current {
		if value, presence := lookupDocumentPath(document, path.legacy); presence != documentMissing {
			return value, presence
		}
	}
	return nil, documentMissing
}

// cpaClientKeyList resolves the client key list and the path it was read from.
//
// The canonical v8 path wins by presence, exactly like every other alias in this
// file. The legacy `api-keys` spelling only resolves to the client keys when it
// is the list: in a v8 document it is the provider-group mapping, and reading a
// mapping as a string list yields nothing. That distinction is what keeps a
// correctly written v8 source from being refused as "holds no client API key".
func cpaClientKeyList(document map[string]any, consumed map[string]bool) ([]string, string, bool) {
	if value, presence := lookupDocumentPath(document, cpaClientKeyPathV8); presence != documentMissing {
		if legacyVal, legacyPresence := lookupDocumentPath(document, cpaClientKeyPathV7); legacyPresence != documentMissing {
			if _, isList := legacyVal.([]any); isList || legacyPresence == documentNull {
				consumed[cpaClientKeyPathV7] = true
			}
		}
		if presence == documentNull {
			consumed[cpaClientKeyPathV8] = true
			return nil, "", false
		}
		return stringList(value), cpaClientKeyPathV8, true
	}
	if value, presence := lookupDocumentPath(document, cpaClientKeyPathV7); presence != documentMissing {
		if presence == documentNull {
			consumed[cpaClientKeyPathV7] = true
			return nil, "", false
		}
		if _, isList := value.([]any); isList {
			return stringList(value), cpaClientKeyPathV7, true
		}
	}
	return nil, "", false
}

// reportUnmapped puts every top-level section or dotted leaf the copy did not
// use on the source as a manual item. Nothing is dropped silently: a top-level
// section the table does not name is reported by name, and a leaf inside a
// mapped section that the table does not name is reported by its dotted path.
func (s *cpaManagedSource) reportUnmapped(document map[string]any, roots, knownContainers, consumed, consumedPrefixes map[string]bool) {
	topLevel := make([]string, 0, len(document))
	for key := range document {
		topLevel = append(topLevel, key)
	}
	sort.Strings(topLevel)
	for _, key := range topLevel {
		if cpaExcludedSourceSections[key] {
			continue
		}
		// A mapped root is walked, even when the removal table also names a
		// section of the same name: `codex` is a mapped root whose one removed
		// leaf is reported by its own path.
		if roots[key] {
			s.reportUnmappedLeaves(key, document, document[key], knownContainers, consumed, consumedPrefixes)
			continue
		}
		if isRemovedSection(key) {
			s.reportRemovedSection(key)
			continue
		}
		if instruction, ok := cpaUnadoptableSections[key]; ok {
			s.addManual(cpaManualItem{
				item:        "section:" + key,
				reason:      "destination_surface_missing",
				instruction: instruction,
			})
			continue
		}
		s.addManual(cpaManualItem{
			item:        "section:" + key,
			reason:      "not_in_import_scope",
			instruction: "The source section " + key + " is outside the CPA state this import copies. Set it on the destination Console if the destination still supports it.",
		})
	}
}

// reportRemovedSection records one section this import knows CPA v8 dropped.
func (s *cpaManagedSource) reportRemovedSection(key string) {
	instruction, ok := cpaRemovedSectionInstruction(key)
	if !ok {
		return
	}
	s.addManual(cpaManualItem{
		item:        "section:" + key,
		reason:      "removed_upstream",
		instruction: instruction,
	})
}

// cpaRemovedSectionInstruction reports the operator instruction of a top-level
// section this import knows CPA v8 no longer has. An `amp-*` sibling is removed
// with the section that declares it, which is why the row names a prefix as well
// as an exact key.
func cpaRemovedSectionInstruction(key string) (string, bool) {
	for _, removed := range cpaRemovedConfigPaths {
		if firstSegment(removed.legacy) == key {
			return removed.instruction, true
		}
		if removed.suffix != "" && strings.HasPrefix(key, removed.suffix) {
			return removed.instruction, true
		}
	}
	return "", false
}

// reportUnmappedLeaves reports the leaves of one mapped section the table does
// not carry.
func (s *cpaManagedSource) reportUnmappedLeaves(section string, document map[string]any, value any, knownContainers, consumed, consumedPrefixes map[string]bool) {
	leaves := map[string]bool{}
	collectDocumentLeaves(section, value, leaves)
	paths := make([]string, 0, len(leaves))
	for path := range leaves {
		if consumed[path] || underConsumedPrefix(path, consumedPrefixes) {
			continue
		}
		if knownContainers[path] && isEmptyContainerOrNull(document, path) {
			continue
		}
		paths = append(paths, path)
	}
	sort.Strings(paths)
	for index, path := range paths {
		if index >= cpaMaxUnmappedLeavesInSection {
			s.addManual(cpaManualItem{
				item:        "section:" + section + "-unmapped",
				reason:      "not_in_import_scope",
				instruction: fmt.Sprintf("%d further keys under %s are outside the CPA state this import copies. Review them on the destination Console.", len(paths)-index, section),
			})
			return
		}
		if reason, instruction, ok := cpaRemovedLeaf(path); ok {
			s.addManual(cpaManualItem{item: "config:" + path, reason: reason, instruction: instruction})
			continue
		}
		s.addManual(cpaManualItem{
			item:        "config:" + path,
			reason:      "not_in_import_scope",
			instruction: "The source setting " + path + " is outside the CPA state this import copies. Set it on the destination Console if the destination still supports it.",
		})
	}
}

// cpaRemovedLeaf names the release a leaf inside a mapped section was removed in.
func cpaRemovedLeaf(path string) (string, string, bool) {
	for _, removed := range cpaRemovedConfigPaths {
		if removed.legacy != path {
			continue
		}
		return "removed_upstream", removed.instruction, true
	}
	return "", "", false
}

// isRemovedSection reports a top-level key this import knows CPA v8 removed.
func isRemovedSection(key string) bool {
	_, ok := cpaRemovedSectionInstruction(key)
	return ok
}

func underConsumedPrefix(path string, consumed map[string]bool) bool {
	for index := strings.LastIndex(path, "."); index > 0; index = strings.LastIndex(path[:index], ".") {
		if consumed[path[:index]] {
			return true
		}
	}
	return false
}

// addManual appends one manual item, bounded by cpaMaxManualItems.
func (s *cpaManagedSource) addManual(item cpaManualItem) {
	if len(s.manual) >= cpaMaxManualItems {
		for index := range s.manual {
			if s.manual[index].item == "cpa-config-unknown-remainder" {
				return
			}
		}
		s.manual = append(s.manual, cpaManualItem{
			item:        "cpa-config-unknown-remainder",
			reason:      "not_in_import_scope",
			instruction: "Further source keys beyond the reported ones are outside the CPA state this import copies. Review the source CPA configuration on the destination Console.",
		})
		return
	}
	for _, existing := range s.manual {
		if existing.item == item.item {
			return
		}
	}
	s.manual = append(s.manual, item)
}

// readCredentials reads the auth directory beside the CPA config.
//
// The directory is the operator's override, then the `auth-dir` the source
// configures when that resolves inside the CPA directory, then the sibling
// `auths` the v1 stack bind-mounts. A source without any of them has no
// credential files, which is a valid state: the run reports zero credentials
// instead of inventing a location.
//
// A `type: gemini` file is excluded from the copy and reported as a manual item:
// CPA v8 silently skips gemini credentials, so uploading one would produce a run
// that claims a copy the destination never lists.
func (s *cpaManagedSource) readCredentials(override string) error {
	directory, ok, err := s.resolveAuthDirectory(override)
	if err != nil {
		return err
	}
	if !ok {
		// A source with no auth directory still has a credential set — the empty
		// one — and the digest is what a retry compares, so it is stamped here
		// rather than left empty for a run that later adds one.
		s.credentialsDigest = s.credentialSetDigest()
		return nil
	}
	s.authDirectory = directory
	entries, err := os.ReadDir(directory)
	if err != nil {
		return newUpgradeError(UpgradeErrorCPASourceMissing, "the managed CPA auth directory could not be read", err)
	}
	for _, entry := range entries {
		if entry.IsDir() || !strings.HasSuffix(strings.ToLower(entry.Name()), ".json") {
			continue
		}
		name := entry.Name()
		path := filepath.Join(directory, name)
		// Every entry that cannot be uploaded becomes a manual item. A skipped
		// file would otherwise be a credential neither the copy count nor the
		// manual list mentions — the silent drop this step exists to avoid.
		info, err := entry.Info()
		if err != nil {
			s.addManual(cpaManualItem{
				item:        "credential:" + name,
				reason:      "credential_unreadable",
				instruction: "The credential file " + name + " could not be inspected, so it was not uploaded. Copy it into the destination CPA auth directory yourself.",
			})
			continue
		}
		if info.Mode()&os.ModeSymlink != 0 {
			s.addManual(cpaManualItem{
				item:        "credential:" + name,
				reason:      "credential_not_regular",
				instruction: "The credential file " + name + " is a symbolic link. This import never follows a link out of the auth directory, so it was not uploaded; copy the file it points at into the destination CPA auth directory yourself.",
			})
			continue
		}
		if !info.Mode().IsRegular() {
			s.addManual(cpaManualItem{
				item:        "credential:" + name,
				reason:      "credential_not_regular",
				instruction: "The credential file " + name + " is not a regular file, so it was not uploaded. Copy it into the destination CPA auth directory yourself.",
			})
			continue
		}
		if info.Size() > cpaMaxAuthFileBytes {
			s.addManual(cpaManualItem{
				item:        "credential:" + name,
				reason:      "credential_too_large",
				instruction: fmt.Sprintf("The credential file %s is %d bytes and this import uploads at most %d bytes per file, so it was not uploaded. Copy it into the destination CPA auth directory yourself.", name, info.Size(), cpaMaxAuthFileBytes),
			})
			continue
		}
		data, _, err := readRegularFileNoFollow(path, cpaMaxAuthFileBytes)
		if err != nil {
			if errors.Is(err, errRegularFileTooLarge) {
				s.addManual(cpaManualItem{
					item:        "credential:" + name,
					reason:      "credential_too_large",
					instruction: fmt.Sprintf("The credential file %s exceeds the %d-byte upload limit, so it was not uploaded. Copy it into the destination CPA auth directory yourself.", name, cpaMaxAuthFileBytes),
				})
				continue
			}
			if errors.Is(err, ErrSourceSymlinked) {
				s.addManual(cpaManualItem{
					item:        "credential:" + name,
					reason:      "credential_not_regular",
					instruction: "The credential file " + name + " is a symbolic link or was replaced during inspection. This import never follows a link out of the auth directory, so it was not uploaded; copy the file it points at into the destination CPA auth directory yourself.",
				})
				continue
			}
			s.addManual(cpaManualItem{
				item:        "credential:" + name,
				reason:      "credential_unreadable",
				instruction: "The credential file " + name + " could not be read, so it was not uploaded. Copy it into the destination CPA auth directory yourself.",
			})
			continue
		}
		credential := freshadopt.CredentialFile{Name: entry.Name()}
		if parsed, ok := credentialMetadata(data); ok {
			credential.Type = parsed.Type
			credential.Disabled = parsed.Disabled
		}
		if strings.EqualFold(credential.Type, "gemini") {
			s.addManual(cpaManualItem{
				item:        "credential:" + entry.Name(),
				reason:      "gemini_credential_unsupported",
				instruction: "CPA v8 never lists a gemini credential, so " + entry.Name() + " was not uploaded. Re-authenticate Gemini on the destination if the destination release supports it.",
			})
			continue
		}
		s.credentials = append(s.credentials, credential)
		s.credentialData[entry.Name()] = data
	}
	sort.Slice(s.credentials, func(i, j int) bool { return s.credentials[i].Name < s.credentials[j].Name })
	s.credentialsDigest = s.credentialSetDigest()
	return nil
}

// credentialSetDigest is the deterministic identity of exactly what this run
// would hand the destination: every uploadable credential's name and byte digest,
// and every credential item the step reports as manual work instead. Manual items
// are part of it because a file that stopped being uploadable is a credential the
// destination would no longer receive, even though config.yaml is unchanged.
func (s *cpaManagedSource) credentialSetDigest() string {
	hasher := sha256.New()
	for _, credential := range s.credentials {
		// The file bytes enter through their digest: the hash never holds the
		// credential itself, only a statement about it.
		_, _ = hasher.Write([]byte("cred:" + credential.Name + "\x00" + digestBytes(s.credentialData[credential.Name]) + "\n"))
	}
	manual := make([]cpaManualItem, 0, len(s.manual))
	for _, item := range s.manual {
		if strings.HasPrefix(item.item, "credential:") {
			manual = append(manual, item)
		}
	}
	sort.Slice(manual, func(i, j int) bool {
		if manual[i].item != manual[j].item {
			return manual[i].item < manual[j].item
		}
		return manual[i].reason < manual[j].reason
	})
	for _, item := range manual {
		_, _ = hasher.Write([]byte("manual:" + item.item + "\x00" + item.reason + "\n"))
	}
	return "sha256:" + hex.EncodeToString(hasher.Sum(nil))
}

// sourceCredentialsDigest is the digest readCredentials stamped. A retry compares
// it with the attempt's record before anything is staged.
func (s *cpaManagedSource) sourceCredentialsDigest() string {
	if s.credentialsDigest == "" {
		return s.credentialSetDigest()
	}
	return s.credentialsDigest
}

// resolveAuthDirectory resolves the source auth directory without following
// symbolic links at the target directory or across relative segments below the
// CPA root.
func (s *cpaManagedSource) resolveAuthDirectory(override string) (string, bool, error) {
	if trimmed := strings.TrimSpace(override); trimmed != "" {
		absolute, err := filepath.Abs(trimmed)
		if err != nil {
			return "", false, fmt.Errorf("resolve the CPA auth directory: %w", err)
		}
		if _, err := statNoFollowDir(absolute); err != nil {
			if errors.Is(err, ErrSourceSymlinked) {
				return "", false, newUpgradeError(UpgradeErrorCPASourceMissing,
					"the named CPA auth directory may not be a symbolic link, so no credentials were read", err)
			}
			return "", false, newUpgradeError(UpgradeErrorCPASourceMissing,
				"the named CPA auth directory does not exist or is not a directory, so no credentials were read", err)
		}
		return absolute, true, nil
	}
	if raw := strings.TrimSpace(s.configuredAuthDir); raw != "" {
		if configured, ok := resolveConfiguredAuthSubdir(s.directory, raw); ok {
			return configured, true, nil
		}
	}
	sibling := filepath.Join(s.directory, cpaAuthDirectoryName)
	info, err := os.Lstat(sibling)
	if err != nil {
		if errors.Is(err, os.ErrNotExist) {
			return "", false, nil
		}
		return "", false, newUpgradeError(UpgradeErrorCPASourceMissing,
			"the managed CPA auth directory could not be inspected", err)
	}
	if info.Mode()&os.ModeSymlink != 0 {
		return "", false, newUpgradeError(UpgradeErrorCPASourceMissing,
			"the managed CPA auths directory may not be a symbolic link, so no credentials were read", ErrSourceSymlinked)
	}
	if !info.IsDir() {
		return "", false, newUpgradeError(UpgradeErrorCPASourceMissing,
			"the managed CPA auths entry is not a directory, so no credentials were read", nil)
	}
	return sibling, true, nil
}

func resolveConfiguredAuthSubdir(baseDir, raw string) (string, bool) {
	var rel string
	if !filepath.IsAbs(raw) {
		rel = filepath.Clean(raw)
	} else {
		cleanedRaw := filepath.Clean(raw)
		canonBase := canonicalPath(baseDir)
		matched := false
		for anc := cleanedRaw; ; {
			if canonicalPath(anc) == canonBase {
				if _, err := statNoFollowDir(anc); err == nil {
					r, relErr := filepath.Rel(anc, cleanedRaw)
					if relErr == nil {
						rel = r
						matched = true
					}
				}
				break
			}
			parent := filepath.Dir(anc)
			if parent == anc {
				break
			}
			anc = parent
		}
		if !matched {
			return "", false
		}
	}
	if rel == "." {
		return baseDir, true
	}
	if rel == "" || rel == ".." || strings.HasPrefix(rel, ".."+string(filepath.Separator)) || filepath.IsAbs(rel) {
		return "", false
	}
	cur := baseDir
	for _, segment := range strings.Split(rel, string(filepath.Separator)) {
		if segment == "" || segment == "." {
			continue
		}
		if segment == ".." {
			return "", false
		}
		cur = filepath.Join(cur, segment)
		if _, err := statNoFollowDir(cur); err != nil {
			return "", false
		}
	}
	return cur, true
}

// credentialType is the two metadata fields this import reads from one
// credential file. Nothing else leaves the file.
type credentialType struct {
	Type     string `json:"type"`
	Disabled bool   `json:"disabled"`
}

func credentialMetadata(data []byte) (credentialType, bool) {
	var parsed credentialType
	if err := json.Unmarshal(data, &parsed); err != nil {
		return credentialType{}, false
	}
	parsed.Type = strings.TrimSpace(parsed.Type)
	return parsed, true
}

// ListCredentialFiles reports the credential files this run may upload.
func (s *cpaManagedSource) ListCredentialFiles(_ context.Context) ([]freshadopt.CredentialFile, error) {
	return slices.Clone(s.credentials), nil
}

// DownloadCredential returns one credential's exact bytes. The caller keeps them
// in memory only.
func (s *cpaManagedSource) DownloadCredential(_ context.Context, name string) ([]byte, error) {
	data, ok := s.credentialData[name]
	if !ok {
		return nil, fmt.Errorf("the 1.x CPA holds no credential file named %q", name)
	}
	return slices.Clone(data), nil
}

