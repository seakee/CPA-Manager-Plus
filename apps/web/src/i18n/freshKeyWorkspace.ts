export function formatKeyListFooterCount(
  kind: 'listed' | 'total',
  count: number,
  languageOverride?: string
): string {
  const language = languageOverride || fullWebLanguage();
  if (language === 'zh-TW') {
    return kind === 'listed' ? `目前顯示 ${count} 把` : `總計 ${count} 把`;
  }
  if (language.startsWith('zh')) {
    return kind === 'listed' ? `当前显示 ${count} 把` : `总计 ${count} 把`;
  }
  if (language === 'ru') {
    const rule = new Intl.PluralRules('ru').select(count);
    const noun = rule === 'one' ? 'ключ' : rule === 'few' ? 'ключа' : 'ключей';
    if (kind === 'listed') {
      const verb = rule === 'one' ? 'Показан' : 'Показано';
      return `${verb} ${count} ${noun}`;
    }
    return `Всего ${count} ${noun}`;
  }
  const noun = new Intl.PluralRules('en').select(count) === 'one' ? 'key' : 'keys';
  return kind === 'listed' ? `Showing ${count} ${noun}` : `Total ${count} ${noun}`;
}

