package upgrade

// This file is the source side of the Managed CPA import: a file-backed reader of
// the 1.x CPA directory that presents the tree through the existing
// freshadopt.Source interface. The step reads it only while it holds the 1.x
// ownership marker (see ImportCPA); the marker proves the 1.x Manager is stopped,
// never that the managed CPA container is. It is deliberately not a general
// configuration converter. It maps exactly the paths this step copies and reports
// everything else the source holds as manual work, so no key is ever dropped
// silently.
//
// # Where the mapping comes from
//
// The table below is derived from the CPA releases, never invented. Two upstream
// readings produce it, and both are checked into the derivation that pins it:
//
//   - the v8 converter, which states the v7 spelling of every v8 path it accepts:
//     internal/config/config_v8.go:18-108 (configPath, v8KeyFamilies,
//     buildV8Paths), :23-58 (v8ClientPaths / v8SharedPaths, the historical
//     spellings of the client.codex.* and upstream.* leaves) and :419-448
//     (groupLegacyKeys, the v7 -> v8 grouping of the *-api-key lists);
//   - the v7 releases themselves, walked from each release's `Config` struct
//     yaml tags, which is what the `introduced` / `removed` columns report.
//
// The independent oracle is testdata/cpa_mapping_upstream.json, generated by
// testdata/gencpamapping from the commits its provenance names.
// TestCPASourceMappingMatchesTheUpstreamAliasTable and its sibling tests compare
// each row with that oracle, so a wrong row fails without a second copy of the
// table in the suite.
//
// # What the columns mean
//
// `introduced` names the exact release the v7 spelling appeared in. When the
// spelling already exists in the first v7 release it is `v7.0.0`: the entry was
// proven present at v7.0.0, v7.2.0, v7.3.4 and v7.3.20, while CPA releases
// below v8 are outside the runtime versions this import accepts. `removed`
// names the exact release the spelling disappeared in, or is empty when it is
// still present in the last v7 release (v7.3.20). Every entry therefore names
// the release that introduced it, the release that removed it, or both.
//
// # What is never mapped
//
// The destination keeps v2's own identity: its management secret, its listener,
// its plugin choice and its client key list belong to the Manager, and the auth
// directory is the one the destination enumerated. A source key under one of
// those is excluded by name and never reported as manual work, because the
// destination's own value is the intended one.
//
// A path in the table is one the step copies. A source path outside the table is
// reported as a manual item: an operator reads it and does the work, which is
// the only alternative to dropping the key.

