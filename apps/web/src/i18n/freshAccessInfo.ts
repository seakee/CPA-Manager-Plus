const dictionaries = { en, zh, tw, ru } as const;
export type FreshAccessInfoTextKey = keyof typeof en;

export function accessInfoText(
  key: FreshAccessInfoTextKey,
  language = fullWebLanguage()
): string {
  const dict = language === 'zh-TW' ? tw : language.startsWith('zh') ? zh : dictionaries[language as keyof typeof dictionaries] ?? en;
  return dict[key] ?? en[key];
}
